% Writes every MATPOWER case in <matpower-dir>/data as a literal-only case file in
%   <output-dir>, for the ybus_powerflow tests. Run through scripts/normalize-cases.sh.
%
% Some MATPOWER case files compute or rescale their data with code after the literals (for
%   example converting loads from kW to MW), which the ybus_powerflow reader deliberately rejects.
%   This runs each file through MATPOWER's own loadcase, which evaluates that code, and writes
%   the resulting case back out as `mpc.<field> = [ ... ];` literals that the reader accepts.
%
% Values are written with %.17g, enough to round-trip a double exactly. MATPOWER's savecase
%   isn't used because it writes %.9g, which would round the values loadcase computed.
%
% Writes version, baseMVA, bus, gen, branch, and gencost and bus_name when present; other
%   fields aren't used by ybus_powerflow. Also writes SOURCE, recording the MATPOWER directory and
%   the versions used. Files that loadcase can't load as a case (such as contingency tables)
%   are listed and skipped.

1;

function write_matrix(fid, name, matrix)
    fprintf(fid, 'mpc.%s = [\n', name);
    if ~isempty(matrix)
        row_format = [repmat('\t%.17g', 1, size(matrix, 2)) ';\n'];
        fprintf(fid, row_format, matrix');
    end
    fprintf(fid, '];\n');
end

function write_case(path, name, mpc)
    fid = fopen(path, 'w');
    fprintf(fid, 'function mpc = %s\n', name);
    fprintf(fid, '%% Generated by scripts/normalize_cases.m from MATPOWER''s %s.m, as loaded\n', name);
    fprintf(fid, '%%   by its loadcase and written as literals at full precision. Don''t edit.\n');
    fprintf(fid, 'mpc.version = ''2'';\n');
    fprintf(fid, 'mpc.baseMVA = %.17g;\n', mpc.baseMVA);
    write_matrix(fid, 'bus', mpc.bus);
    write_matrix(fid, 'gen', mpc.gen);
    write_matrix(fid, 'branch', mpc.branch);
    if isfield(mpc, 'gencost') && ~isempty(mpc.gencost)
        write_matrix(fid, 'gencost', mpc.gencost);
    end
    if isfield(mpc, 'bus_name')
        fprintf(fid, 'mpc.bus_name = {\n');
        for k = 1:numel(mpc.bus_name)
            % Quotes inside a MATLAB string are doubled
            fprintf(fid, '\t''%s'';\n', strrep(mpc.bus_name{k}, '''', ''''''));
        end
        fprintf(fid, '};\n');
    end
    fclose(fid);
end

args = argv();
if numel(args) ~= 2
    error('usage: normalize_cases.m <matpower-dir> <output-dir>');
end
[matpower_dir, out_dir] = deal(args{1}, args{2});
addpath(genpath(matpower_dir));

files = dir(fullfile(matpower_dir, 'data', '*.m'));
written = 0;
skipped = {};
for k = 1:numel(files)
    [~, name] = fileparts(files(k).name);
    try
        mpc = loadcase(name);
    catch err
        skipped{end + 1} = sprintf('%s (%s)', name, err.message);
        continue;
    end
    if ~(isstruct(mpc) && all(isfield(mpc, {'baseMVA', 'bus', 'gen', 'branch'})))
        skipped{end + 1} = sprintf('%s (not a case)', name);
        continue;
    end
    write_case(fullfile(out_dir, [name '.m']), name, mpc);
    written = written + 1;
end

% Where the data came from, so the tests can tell when the output is stale
fid = fopen(fullfile(out_dir, 'SOURCE'), 'w');
fprintf(fid, 'source %s\nMATPOWER %s\nOctave %s\n', matpower_dir, mpver, OCTAVE_VERSION);
fclose(fid);

printf('normalized %d cases into %s\n', written, out_dir);
for k = 1:numel(skipped)
    printf('skipped %s\n', skipped{k});
end
